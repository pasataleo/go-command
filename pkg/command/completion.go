package command

import (
	"fmt"
	"slices"
	"sort"
	"strings"

	"github.com/pasataleo/go-config/pkg/flags"
	"github.com/pasataleo/go-errorsx/pkg/errorsx"
)

// CompletionScript generates a shell completion script for the given shell.
// Supported shells are "bash", "zsh", and "fish".
func (commands *Commands) CompletionScript(shell string) (string, error) {
	switch shell {
	case "bash":
		return commands.bashCompletion(), nil
	case "zsh":
		return commands.zshCompletion(), nil
	case "fish":
		return commands.fishCompletion(), nil
	default:
		return "", errorsx.Newf(errorsx.InvalidArgument, nil, "unsupported shell %q: must be one of bash, zsh, fish", shell)
	}
}

// complete returns the list of valid completions for the given command and
// partial word. command is the already-navigated command; current is the
// partial word being typed (may be empty or start with "-" for flags).
func (commands *Commands) complete(command *Command, current string, found map[string]map[string]interface{}) []string {
	var completions []string

	if strings.HasPrefix(current, "-") {
		completions = append(completions, "--"+helpCommand)
		if command == commands.Root && commands.Version != "" {
			completions = append(completions, "--"+versionCommand)
		}
		for _, flag := range collectFlags(found, command.FlagDocs) {
			completions = append(completions, "--"+flag.Name)
		}
	} else {
		completions = append(completions, helpCommand)
		if command == commands.Root {
			if commands.Version != "" {
				completions = append(completions, versionCommand)
			}
			completions = append(completions, completionCommand)
		}
		for name, child := range command.Children {
			if !child.Hidden {
				completions = append(completions, name)
			}
		}
	}

	sort.Strings(completions)
	return completions
}

// -- shell scripts --

func sanitizeFuncName(name string) string {
	return strings.NewReplacer("-", "_", ".", "_").Replace(name)
}

func (commands *Commands) bashCompletion() string {
	fname := "_" + sanitizeFuncName(commands.Command)
	cmd := commands.Command
	return fmt.Sprintf(`# Generated by: %s completion bash
# Source this file or place it in ~/.bash_completion.d/

%s() {
    local cur nav
    COMPREPLY=()
    cur="${COMP_WORDS[COMP_CWORD]}"
    nav=("${COMP_WORDS[@]:1:$((COMP_CWORD-1))}")
    COMPREPLY=($(compgen -W "$(%s "${nav[@]}" __complete "$cur")" -- "$cur"))
}

complete -F %s %s
`, cmd, fname, cmd, fname, cmd)
}

func (commands *Commands) zshCompletion() string {
	fname := "_" + sanitizeFuncName(commands.Command)
	cmd := commands.Command
	return fmt.Sprintf(`#compdef %s
# Generated by: %s completion zsh
# Place this file in a directory on your $fpath

function %s {
    local -a completions
    completions=(${(f)"$(${words[1]} ${words[2,CURRENT-1]} __complete ${words[CURRENT]})"})
    compadd -a completions
}

%s
`, cmd, cmd, fname, fname)
}

func (commands *Commands) fishCompletion() string {
	fname := "__" + sanitizeFuncName(commands.Command) + "_completions"
	cmd := commands.Command
	return fmt.Sprintf(`# Generated by: %s completion fish
# Place this file at ~/.config/fish/completions/%s.fish

function %s
    set -l tokens (commandline -opc)
    %s $tokens[2..-2] __complete $tokens[-1]
end

complete -c %s -f -a "(%s)"
`, cmd, cmd, fname, cmd, cmd, fname)
}

// -- metadata collection --

type completionEnvVar struct {
	name        string
	desc        string
	def         string
	requirement string
}

// collectFlags documents every flag a command takes, sorted by name: each
// config flag in meta from its tags, and each flag the command documents
// itself as it gave it.
func collectFlags(meta map[string]map[string]interface{}, documented []FlagDoc) []FlagDoc {
	result := slices.Clone(documented)
	required := requirements(meta)
	for path, sources := range meta {
		if sources["hidden"] != nil {
			continue
		}
		flagValue, ok := sources["flags"].(flags.Flag)
		if !ok {
			continue
		}
		usage, _ := sources["usage"].(string)
		def, _ := sources["defaults"].(string)
		result = append(result, FlagDoc{Flag: flagValue, Usage: usage, Default: def, Requirement: required[path]})
	}
	sort.Slice(result, func(i, j int) bool {
		return result[i].Name < result[j].Name
	})
	return result
}

func collectCompletionEnvVars(meta map[string]map[string]interface{}) []completionEnvVar {
	var result []completionEnvVar
	required := requirements(meta)
	for path, sources := range meta {
		if sources["hidden"] != nil {
			continue
		}
		envName, ok := sources["env"].(string)
		if !ok {
			continue
		}
		desc, _ := sources["usage"].(string)
		def, _ := sources["defaults"].(string)
		result = append(result, completionEnvVar{name: envName, desc: desc, def: def, requirement: required[path]})
	}
	sort.Slice(result, func(i, j int) bool {
		return result[i].name < result[j].name
	})
	return result
}
